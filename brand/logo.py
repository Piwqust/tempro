"""Tempro's logo files, generated. Run from the repo root:  python brand/logo.py

Writes brand/logo/*.svg and app/src/ui/wordmark.ts. The mark is a week drawn as a heat map,
today in the signal orange. The wordmark is "tempro" in Inter SemiBold (SIL Open Font License),
outlined, so the files need no font. Inter comes from the app's own dependency:
app/node_modules/@fontsource-variable/inter (run `bun install` in app/ first).
"""
import io
import math
import os

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "logo")
APP = os.path.join(ROOT, "..", "app")
INTER = os.path.join(APP, "node_modules", "@fontsource-variable", "inter", "files", "inter-latin-wght-normal.woff2")

INK = "#14151C"
PAPER = "#F6F6F8"
SIGNAL = "#FF5A1F"
WEIGHT = 600
TRACKING = -0.02


def mark(fg: str, now: str = SIGNAL) -> str:
    """A week as a heat map on a 64 grid: how full each day was, today lit."""
    levels = [[0.22, 0.55, 1.0], [0.55, 1.0, 0.3], [1.0, 0.45, None]]
    out = ""
    for r, row in enumerate(levels):
        for c, op in enumerate(row):
            x, y = 7 + c * 18, 7 + r * 18
            fill = now if op is None else fg
            o = "" if op is None else f' opacity="{op}"'
            out += f'<rect x="{x}" y="{y}" width="14" height="14" rx="4" fill="{fill}"{o}/>'
    return out


def outline(text: str, size: float) -> tuple[str, float, float]:
    """(path d with the baseline at y = 0, advance width, x-height) in px."""
    f = instantiateVariableFont(TTFont(INTER), {"wght": WEIGHT})
    upm = f["head"].unitsPerEm
    k = size / upm
    cmap, gs, hmtx = f.getBestCmap(), f.getGlyphSet(), f["hmtx"]
    pen = SVGPathPen(gs, lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    x = 0.0
    for ch in text:
        g = cmap[ord(ch)]
        gs[g].draw(TransformPen(pen, (k, 0, 0, -k, x * k, 0)))
        x += hmtx[g][0] + TRACKING * upm
    x -= TRACKING * upm
    xh = (getattr(f["OS/2"], "sxHeight", 0) or upm * 0.5) * k
    return pen.getCommands(), x * k, xh


def svg(w: float, h: float, body: str) -> str:
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:g} {h:g}" width="{w:g}" height="{h:g}" role="img" aria-label="Tempro">{body}</svg>'


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    size, height = 40, 44
    d, w, xh = outline("tempro", size)
    width = math.ceil(w) + 2
    baseline = round((height + xh) / 2, 2)

    def lockup(fg: str) -> str:
        m, gap, h = 48, 14, 56
        return svg(m + gap + width, h,
                   f'<g transform="translate(0 {(h - m) / 2:g}) scale({m / 64:g})">{mark(fg)}</g>'
                   f'<g transform="translate({m + gap} {h / 2 + xh / 2:.2f})"><path d="{d}" fill="{fg}"/></g>')

    files = {
        "mark.svg": svg(64, 64, mark(INK)),
        "mark-dark.svg": svg(64, 64, mark(PAPER)),
        "mark-mono.svg": svg(64, 64, mark("currentColor", "currentColor")),
        "icon.svg": svg(64, 64, f'<rect width="64" height="64" rx="15" fill="{INK}"/>' + mark(PAPER)),
        "lockup.svg": lockup(INK),
        "lockup-dark.svg": lockup(PAPER),
        "wordmark.svg": svg(width, height, f'<g transform="translate(0 {baseline:g})"><path d="{d}" fill="{INK}"/></g>'),
    }
    for name, text in files.items():
        with io.open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text + "\n")
    with io.open(os.path.join(APP, "src", "ui", "wordmark.ts"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by brand/logo.py (Inter SemiBold, outlined). Do not edit by hand.\n")
        f.write(f'export const WORDMARK = {{ width: {width}, height: {height}, baseline: {baseline:g}, d: "{d}" }};\n')
    print("wrote", ", ".join(files), "and app/src/ui/wordmark.ts")


if __name__ == "__main__":
    main()
